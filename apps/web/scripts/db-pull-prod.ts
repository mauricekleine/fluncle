#!/usr/bin/env bun

import { $ } from "bun";
import { createClient } from "@libsql/client/web";
import { parseArgs } from "node:util";

import { REMOTE_DB_CONCURRENCY } from "../src/lib/database-concurrency";
import { resolveProductionCredentials } from "./lib/prod-credentials";
import {
  devSnapshotPath,
  formatSnapshotReport,
  pullSnapshot,
  SNAPSHOT_PAGE_ROWS,
} from "./lib/db-snapshot";

async function runForStdout(command: string[]): Promise<string> {
  const result = await $`${command}`.quiet().nothrow();

  if (result.exitCode !== 0) {
    throw new Error(result.stderr.toString().trim() || `exit code ${result.exitCode}`);
  }

  return result.stdout.toString();
}

function pageRowsFrom(raw: string | undefined): number {
  if (raw === undefined) {
    return SNAPSHOT_PAGE_ROWS;
  }

  const value = Number(raw);

  if (!Number.isInteger(value) || value < 1) {
    throw new Error(`--page-rows must be a positive integer, got "${raw}".`);
  }

  return value;
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: { "if-missing": { type: "boolean" }, "page-rows": { type: "string" } },
    strict: true,
  });
  const pageRows = pageRowsFrom(values["page-rows"]);
  const { authToken, describe, url } = await resolveProductionCredentials(
    process.env,
    runForStdout,
  );

  console.log(`Production credentials: ${describe}.`);

  const client = createClient({
    authToken,
    concurrency: REMOTE_DB_CONCURRENCY,
    intMode: "bigint",
    url,
  });

  try {
    const outPath = devSnapshotPath();

    console.log(`Pulling production into ${outPath}, ${pageRows} rows per request…`);

    const report = await pullSnapshot({
      client,
      header:
        "-- Fluncle production snapshot. Generated by `bun run db:pull-prod`. Do not edit by hand.",
      ifMissing: values["if-missing"] === true,
      log: (line) => console.log(line),
      outPath,
      pageRows,
    });

    if (report) {
      console.log(formatSnapshotReport(report));
    }
  } finally {
    client.close();
  }
}

try {
  await main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
